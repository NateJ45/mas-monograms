// Run via (from the REPO ROOT; this lived in studio/scripts/ until 2026-08-28, when the
// nested studio/ package was folded into the root one):
//   npx sanity exec scripts/apply-asset-patches.mjs --with-user-token              # dry run
//   NCS_PRODUCTION_WRITE=yes npx sanity exec scripts/apply-asset-patches.mjs --with-user-token -- --apply
// Dry by default, and the write needs the production second factor
// (scripts/lib/write-gate.mjs, starter PORTS.md card 86). Nathan or a delegated agent
// sets it, only under the write protocol (backup, dry run, apply, verify).
//
// Reads the NDJSON of asset patches generated by
// scripts/enrich-asset-metadata.mjs (../tmp/enrich-asset-patches.ndjson) and
// applies each as a granular Sanity patch using the CLI user's auth.
//
// Why this exists: `sanity dataset import --replace` rejects asset-type docs
// because they're missing immutable asset properties (assetId, sha1hash, etc).
// The client.patch() API doesn't care about that, but using the SANITY_API_WRITE_TOKEN
// directly hit a "project user not found" membership error. The CLI exec
// context uses the Sanity CLI's bundled user session (Nathan's Administrator
// account), which has full project membership and can patch anything.
//
// Batched via client.transaction() — 172 patches go up as one request.

import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeGate } from './lib/write-gate.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
// ONE '..' since 2026-08-28: this file moved from studio/scripts/ to scripts/
// when the nested studio package was folded into the root one, so it is now a
// single level below the repo root instead of two. Left unchanged it resolved to
// a sibling of the repo and the read would have failed with ENOENT.
const ndjsonPath = resolve(__dirname, '..', 'tmp', 'enrich-asset-patches.ndjson');

// The CLI client's dataset comes from sanity.cli.ts; this project only has
// `production`, so the gate treats the run as production whatever it says.
const APPLY = writeGate({ dataset: 'production' });

const docs = readFileSync(ndjsonPath, 'utf-8')
  .trim()
  .split('\n')
  .map((line) => JSON.parse(line));

console.log(`Loaded ${docs.length} asset patches from ${ndjsonPath}`);

if (!APPLY) {
  for (const doc of docs) console.log(`would set title/altText/description/opt on ${doc._id}`);
  process.exit(0);
}

// Loaded only for a real write, after the gate (it is slow to import).
const { getCliClient } = await import('sanity/cli');
const client = getCliClient({ apiVersion: '2025-02-19' });

// Build one transaction with all patches.
let tx = client.transaction();
for (const doc of docs) {
  tx = tx.patch(doc._id, (p) =>
    p.set({
      title: doc.title,
      altText: doc.altText,
      description: doc.description,
      opt: doc.opt,
    }),
  );
}

console.log(`Committing transaction with ${docs.length} patches...`);
const result = await tx.commit({ autoGenerateArrayKeys: true });
console.log(`Done. Server returned transaction id: ${result.transactionId}`);
console.log(`Mutated ${result.results.length} assets.`);
