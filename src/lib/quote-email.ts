export function escapeHtml(input: string): string {
  return String(input)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/** Escape, then keep the visitor's line breaks. */
const escLines = (s: string) => escapeHtml(s).replace(/\r?\n/g, '<br/>');

/**
 * The initials the quote prefill writes into Personalization ("Your initials: ABC",
 * the label comes from atelierSettings), so the email can set them large. Only a
 * short run of letters, digits, `&`, dots, spaces or hyphens counts.
 */
export function parseInitials(personalization: string): string | null {
  for (const line of personalization.split(/\r?\n/)) {
    const m = line.match(/initials?\s*:\s*([A-Za-z0-9&.\- ]{1,9})\s*$/i);
    if (m && m[1].trim()) return m[1].trim();
  }
  return null;
}

/** "Fabric: Natural linen" from the prefill's Item description line, if present. */
export function parseFabric(itemDescription: string): string | null {
  for (const line of itemDescription.split(/\r?\n/)) {
    const m = line.match(/^\s*fabric\s*:\s*(.{1,64})$/i);
    if (m && m[1].trim()) return m[1].trim();
  }
  return null;
}

/** "2026-12-01" (the date input) reads as "Tue, Dec 1, 2026"; anything else is shown as typed. */
export function formatNeededBy(value: string): string {
  const m = value.match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (!m) return value;
  const d = new Date(Date.UTC(+m[1], +m[2] - 1, +m[3]));
  if (Number.isNaN(d.getTime()) || d.getUTCDate() !== +m[3]) return value;
  return d.toLocaleDateString('en-US', {
    weekday: 'short',
    month: 'short',
    day: 'numeric',
    year: 'numeric',
    timeZone: 'UTC',
  });
}

/** Digits (and a leading +) for a tel: link; null when it is not a usable number. */
export function telHref(phone: string): string | null {
  const digits = phone.replace(/[^\d+]/g, '');
  return digits.replace(/\D/g, '').length >= 7 ? `tel:${digits}` : null;
}

