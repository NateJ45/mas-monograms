// =============================================================================
// quote-email - the two emails the quote Worker sends (2026-10-05)
// =============================================================================
// src/pages/api/quote.ts validates the form, backs it up to R2 and sends two
// messages through the Cloudflare Email Service binding. This module only builds
// them: the owner notification Mary Ann reads (usually on her phone) and the
// customer confirmation. Both are designed pieces in the Atelier language:
//
//   - a Linen page with a Paper card, under a Midnight band that carries the gold
//     Hoop Seal and the Signature Thread wordmark (hosted PNGs on a solid Midnight
//     ground, generated by scripts/generate-favicons.mjs);
//   - a thread-gold rule under the band and running-stitch dividers (dashed brass
//     borders); headings in a serif stack that echoes Fraunces; Claret only for the
//     one action and the rush flag.
//
// Email constraints this respects: table layout, inline styles only, 600px max,
// no web fonts, no SVG, no background images, no flex or grid, a bulletproof
// button built from a table cell, images by absolute URL with width, height and
// alt, nothing that stops reading when images are blocked, no pure white (so a
// client that inverts colours keeps the contrast), a hidden preheader, and a
// plain-text twin written out by hand rather than stripped from the HTML.
//
// SAFETY: every value that came from the form passes through escapeHtml() before
// it touches the HTML, including attributes (mailto:, tel:). Unit tests in
// quote-email.test.ts feed it hostile input.
//
// Copy rules: only claims the site already makes (reply within 1 business day, a
// custom itemized quote by email, nothing is stitched until the customer
// approves). The three "what happens next" lines and the contact details come
// from Sanity at send time when available (thankYouPage.nextSteps,
// siteSettings.email / phone / address), with the same words as fallbacks.
// =============================================================================

