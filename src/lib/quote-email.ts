function contactFooter(ctx: EmailContext, extra = ''): string {
  const name = escapeHtml(ctx.businessName || 'MAS Monograms');
  const place = [ctx.city, ctx.state]
    .filter((v): v is string => !!v)
    .map((v) => escapeHtml(v))
    .join(', ');
  const lines = [
    `<strong style="font-family:${SERIF};font-size:15px;font-weight:normal;color:${C.midnight};">${name}</strong>${place ? `, ${place}` : ''}`,
  ];
  const reach: string[] = [link(SITE_URL, 'mas-monograms.com')];
  if (ctx.email) reach.push(link(`mailto:${escapeHtml(ctx.email)}`, escapeHtml(ctx.email)));
  const tel = ctx.phone ? telHref(ctx.phone) : null;
  if (ctx.phone && tel) reach.push(link(escapeHtml(tel), escapeHtml(ctx.phone)));
  lines.push(reach.join(' &nbsp;&middot;&nbsp; '));
  if (extra) lines.push(extra);
  return lines.map((l) => `<p style="margin:0 0 4px 0;">${l}</p>`).join('');
}

function contactText(ctx: EmailContext): string {
  const place = [ctx.city, ctx.state].filter(Boolean).join(', ');
  return [
    `${ctx.businessName || 'MAS Monograms'}${place ? `, ${place}` : ''}`,
    [SITE_URL, ctx.email, ctx.phone].filter(Boolean).join(' | '),
  ].join('\n');
}

/** Plain-text label/value block. */
function textBlock(
  title: string,
  rows: Array<[string, string | null | undefined | false]>,
): string {
  const kept = rows.filter(([, v]) => v) as Array<[string, string]>;
  if (!kept.length) return '';
  return `${title.toUpperCase()}\n${kept.map(([l, v]) => `${l}: ${v.replace(/\r?\n/g, '\n  ')}`).join('\n')}`;
}

/** The monogram panel: initials set large when the prefill supplied them. */
function monogramPanel(s: QuoteSubmission, initials: string | null, fabric: string | null): string {
  const meta = [s.monogramStyle, s.threadColor && `${s.threadColor} thread`, fabric]
    .filter(Boolean)
    .map((v) => escapeHtml(v as string))
    .join(' &nbsp;&middot;&nbsp; ');
  const big = initials
    ? `<p style="margin:0 0 6px 0;font-family:${SERIF};font-size:44px;line-height:1.1;letter-spacing:0.12em;color:${C.midnight};">${escapeHtml(initials)}</p>`
    : `<p style="margin:0 0 8px 0;font-family:${SERIF};font-size:19px;line-height:1.45;color:${C.midnight};word-break:break-word;overflow-wrap:anywhere;">${escLines(s.personalization)}</p>`;
  return `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="margin:6px 0 4px 0;"><tr><td align="center" bgcolor="${C.well}" style="background-color:${C.well};border:2px dashed ${C.brass};border-radius:10px;padding:22px 18px;">${big}${meta ? `<p style="margin:0;font-family:${SANS};font-size:14px;line-height:1.5;color:${C.muted};">${meta}</p>` : ''}</td></tr></table>`;
}

// ── Customer confirmation ──────────────────────────────────────────────────────
export function buildCustomerEmail(s: QuoteSubmission, ctx: EmailContext = {}): BuiltEmail {
  const first = firstName(s.name);
  const initials = parseInitials(s.personalization);
  const fabric = parseFabric(s.itemDescription);
  const steps = ctx.nextSteps?.filter(Boolean).length ? ctx.nextSteps! : FALLBACK_NEXT_STEPS;
  const stepsLabel = ctx.nextStepsLabel || "What's next";
  const contactLine = [
    ctx.email ? link(`mailto:${escapeHtml(ctx.email)}`, escapeHtml(ctx.email)) : '',
    ctx.phone && telHref(ctx.phone)
      ? link(escapeHtml(telHref(ctx.phone)!), escapeHtml(ctx.phone))
      : '',
  ]
    .filter(Boolean)
    .join(' or ');

  const item = `${escapeHtml(s.itemType)}${s.quantity ? ` (${escapeHtml(s.quantity)})` : ''}`;
  const summary = details([
    ['Item', item],
    ['Your own item?', escapeHtml(s.ownership)],
    ['About the item', s.itemDescription && escLines(s.itemDescription)],
    ['Personalization', initials ? escLines(s.personalization) : null],
    ['Style', escapeHtml(s.monogramStyle)],
    ['Placement', escapeHtml(s.placement)],
    ['Size', escapeHtml(s.size)],
    ['Thread colors', escapeHtml(s.threadCount)],
    ['Font', s.fontPreference && escapeHtml(s.fontPreference)],
    ['Thread color', s.threadColor && escapeHtml(s.threadColor)],
    ['Needed by', s.neededBy && escapeHtml(formatNeededBy(s.neededBy))],
    ['Gift', s.isGift ? 'Yes' : null],
    [
      'Rush',
      s.isRush ? `<strong style="color:${C.claret};">Yes, a rush fee may apply</strong>` : null,
    ],
    ['Photos', s.attachmentNames.length ? escapeHtml(s.attachmentNames.join(', ')) : null],
  ]);

  const stepRows = steps
    .map(
      (step, i) =>
        `<tr><td valign="top" width="40" style="padding:0 12px 14px 0;"><table role="presentation" cellpadding="0" cellspacing="0" border="0"><tr><td align="center" width="30" height="30" style="width:30px;height:30px;border:2px solid ${C.gold};border-radius:999px;font-family:${SERIF};font-size:15px;line-height:30px;color:${C.midnight};">${i + 1}</td></tr></table></td><td valign="top" style="padding:5px 0 14px 0;font-family:${SANS};font-size:15px;line-height:1.55;color:${C.ink};">${escapeHtml(step)}</td></tr>`,
    )
    .join('');

  const body = [
    h1(`Thank you, ${escapeHtml(first)}.`),
    para(
      "Your quote request is in, and it's on its way to my inbox. I read every one personally, and I'll be in touch within 1 business day to discuss your order.",
    ),
    monogramPanel(s, initials, fabric),
    stitch(26, 22),
    h2('What you asked for'),
    summary,
    stitch(24, 22),
    h2(escapeHtml(stepsLabel)),
    `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0">${stepRows}</table>`,
    para(
      'Nothing is stitched and nothing is charged until you approve your quote.',
      `color:${C.muted};font-size:15px;`,
    ),
    stitch(10, 22),
    para(
      contactLine
        ? `Questions in the meantime? You can reach me at ${contactLine}.`
        : `Questions in the meantime? You can reach me through ${link(SITE_URL, 'mas-monograms.com')}.`,
    ),
    `<p style="margin:18px 0 0 0;font-family:${SERIF};font-size:22px;font-style:italic;line-height:1.3;color:${C.midnight};">Mary Ann</p>`,
    `<p style="margin:2px 0 0 0;font-family:${SANS};font-size:13px;line-height:1.4;color:${C.muted};">${escapeHtml(ctx.businessName || 'MAS Monograms')}</p>`,
  ].join('\n');

  const html = shell({
    title: 'We got your quote request',
    preheader: `Thanks, ${escapeHtml(first)}. I'll be in touch within 1 business day.`,
    body,
    footer: contactFooter(
      ctx,
      'You are getting this because you asked for a quote on our website.',
    ),
  });

  const text = [
    'MAS Monograms',
    '',
    `Thank you, ${first}.`,
    '',
    "Your quote request is in, and it's on its way to my inbox. I read every one personally, and I'll be in touch within 1 business day to discuss your order.",
    '',
    textBlock('What you asked for', [
      ['Item', `${s.itemType}${s.quantity ? ` (${s.quantity})` : ''}`],
      ['Your own item?', s.ownership],
      ['About the item', s.itemDescription],
      ['Personalization', s.personalization],
      ['Style', s.monogramStyle],
      ['Placement', s.placement],
      ['Size', s.size],
      ['Thread colors', s.threadCount],
      ['Font', s.fontPreference],
      ['Thread color', s.threadColor],
      ['Needed by', s.neededBy && formatNeededBy(s.neededBy)],
      ['Gift', s.isGift ? 'Yes' : null],
      ['Rush', s.isRush ? 'Yes, a rush fee may apply' : null],
      ['Photos', s.attachmentNames.join(', ')],
    ]),
    '',
    stepsLabel.toUpperCase(),
    ...steps.map((step, i) => `${i + 1}. ${step}`),
    '',
    'Nothing is stitched and nothing is charged until you approve your quote.',
    '',
    `Questions in the meantime? ${[ctx.email, ctx.phone].filter(Boolean).join(' or ') || SITE_URL}`,
    '',
    'Mary Ann',
    '',
    '---',
    contactText(ctx),
  ].join('\n');

  return { subject: 'We got your quote request! | MAS Monograms', html, text };
}

// ── Owner notification ─────────────────────────────────────────────────────────
export function buildOwnerEmail(s: QuoteSubmission, ctx: EmailContext = {}): BuiltEmail {
  const when = s.submittedAt.toLocaleString('en-US', {
    timeZone: 'America/New_York',
    dateStyle: 'medium',
    timeStyle: 'short',
  });
  const initials = parseInitials(s.personalization);
  const fabric = parseFabric(s.itemDescription);
  const eEmail = escapeHtml(s.email);
  const tel = s.phone ? telHref(s.phone) : null;
  const replyHref = escapeHtml(
    `mailto:${s.email}?subject=${encodeURIComponent('Your MAS Monograms quote')}`,
  );
  const item = `${escapeHtml(s.itemType)}${s.quantity ? ` (${escapeHtml(s.quantity)})` : ''}`;
  // "QR code on a hang tag or label (campaign fall-fair)"; null (row hidden) with no tags.
  const foundVia = describeUtm(s.utm);

  const actions = `<table role="presentation" cellpadding="0" cellspacing="0" border="0" style="margin:6px 0 8px 0;"><tr><td style="padding:0 0 12px 0;">${button(replyHref, 'Reply by email')}</td></tr>${tel ? `<tr><td style="padding:0 0 12px 4px;font-family:${SANS};font-size:16px;line-height:1.3;">${link(escapeHtml(tel), `Call ${escapeHtml(s.phone)}`)}</td></tr>` : ''}</table>`;

  const keyFacts = details([
    [
      'Needed by',
      s.neededBy
        ? `<strong style="color:${C.midnight};">${escapeHtml(formatNeededBy(s.neededBy))}</strong>`
        : 'No date given',
    ],
    ['Rush?', s.isRush ? `<strong style="color:${C.claret};">Yes, rush requested</strong>` : 'No'],
    ['Gift?', s.isGift ? 'Yes' : 'No'],
  ]);

  const section = (title: string, rows: Array<[string, string | null | undefined | false]>) => {
    const t = details(rows);
    return t ? `${stitch(22, 18)}${h2(title)}${t}` : '';
  };

  const body = [
    s.isRush ? rushBadge('RUSH REQUESTED') : '',
    h1(escapeHtml(s.name)),
    para(
      `would like a quote for <strong style="color:${C.midnight};">${item}</strong>.`,
      'margin-top:-6px;',
    ),
    actions,
    keyFacts,
    section('Contact', [
      ['Name', escapeHtml(s.name)],
      ['Email', link(`mailto:${eEmail}`, eEmail)],
      [
        'Phone',
        s.phone
          ? tel
            ? link(escapeHtml(tel), escapeHtml(s.phone))
            : escapeHtml(s.phone)
          : 'Not given',
      ],
      ['Heard about us', s.referral && escapeHtml(s.referral)],
      ['Where they found you', foundVia && escapeHtml(foundVia)],
    ]),
    section('Item', [
      ['Item type', escapeHtml(s.itemType)],
      ['Owns the item?', escapeHtml(s.ownership)],
      ['Description', s.itemDescription && escLines(s.itemDescription)],
      ['Quantity', s.quantity && escapeHtml(s.quantity)],
    ]),
    `${stitch(22, 18)}${h2('Monogram')}`,
    monogramPanel(s, initials, fabric),
    `<div style="height:10px;line-height:10px;font-size:0;">&nbsp;</div>`,
    details([
      ['Personalization', escLines(s.personalization)],
      ['Style', escapeHtml(s.monogramStyle)],
      ['Placement', escapeHtml(s.placement)],
      ['Size', escapeHtml(s.size)],
      ['Thread colors', escapeHtml(s.threadCount)],
      ['Font', s.fontPreference && escapeHtml(s.fontPreference)],
      ['Thread color', s.threadColor && escapeHtml(s.threadColor)],
    ]),
    s.notes ? `${stitch(22, 18)}${h2('Notes')}${para(escLines(s.notes))}` : '',
    s.attachmentNames.length
      ? section('Photos attached', [['Files', escapeHtml(s.attachmentNames.join(', '))]])
      : '',
    stitch(22, 14),
    `<p style="margin:0;font-family:${SANS};font-size:12px;line-height:1.5;color:${C.muted};">Reply to this email to answer ${escapeHtml(firstName(s.name))} directly. Received ${escapeHtml(when)}. Submission ID ${escapeHtml(s.submissionId)}</p>`,
  ].join('\n');

  const html = shell({
    title: 'New quote request',
    preheader: `${s.isRush ? 'RUSH. ' : ''}${escapeHtml(s.name)}: ${item}${s.neededBy ? `, needed by ${escapeHtml(formatNeededBy(s.neededBy))}` : ''}`,
    bandLine: 'New quote request',
    body,
    footer: contactFooter(ctx),
  });

  const text = [
    'MAS Monograms: new quote request',
    '',
    s.isRush ? '*** RUSH REQUESTED ***\n' : '',
    `${s.name} would like a quote for ${s.itemType}${s.quantity ? ` (${s.quantity})` : ''}.`,
    `Needed by: ${s.neededBy ? formatNeededBy(s.neededBy) : 'No date given'}`,
    `Reply: ${s.email}${s.phone ? `  |  Call: ${s.phone}` : ''}`,
    '',
    textBlock('Contact', [
      ['Name', s.name],
      ['Email', s.email],
      ['Phone', s.phone || 'Not given'],
      ['Heard about us', s.referral],
      ['Where they found you', foundVia],
    ]),
    '',
    textBlock('Item', [
      ['Item type', s.itemType],
      ['Owns the item?', s.ownership],
      ['Description', s.itemDescription],
      ['Quantity', s.quantity],
    ]),
    '',
    textBlock('Monogram', [
      ['Personalization', s.personalization],
      ['Style', s.monogramStyle],
      ['Placement', s.placement],
      ['Size', s.size],
      ['Thread colors', s.threadCount],
      ['Font', s.fontPreference],
      ['Thread color', s.threadColor],
    ]),
    '',
    textBlock('Logistics', [
      ['Needed by', s.neededBy && formatNeededBy(s.neededBy)],
      ['Rush?', s.isRush ? 'Yes, rush requested' : 'No'],
      ['Gift?', s.isGift ? 'Yes' : 'No'],
    ]),
    s.notes ? `\nNOTES\n${s.notes}` : '',
    s.attachmentNames.length ? `\nPHOTOS ATTACHED\n${s.attachmentNames.join(', ')}` : '',
    '',
    `Received ${when}. Submission ID ${s.submissionId}`,
  ]
    .filter((line, i, all) => !(line === '' && all[i - 1] === ''))
    .join('\n');

  return { subject: `New Quote Request from ${s.name}`, html, text };
}
