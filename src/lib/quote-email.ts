const stitch = (top = 24, bottom = 24) =>
  `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0"><tr><td style="padding:${top}px 0 ${bottom}px 0;"><div style="border-top:2px dashed ${C.brass};height:0;line-height:0;font-size:0;">&nbsp;</div></td></tr></table>`;

const h1 = (inner: string) =>
  `<h1 style="margin:0 0 12px 0;font-family:${SERIF};font-size:28px;line-height:1.2;font-weight:normal;color:${C.midnight};">${inner}</h1>`;

const h2 = (inner: string) =>
  `<h2 style="margin:0 0 12px 0;font-family:${SERIF};font-size:20px;line-height:1.3;font-weight:normal;color:${C.indigo};">${inner}</h2>`;

const para = (inner: string, extra = '') =>
  `<p style="margin:0 0 14px 0;font-family:${SANS};font-size:16px;line-height:1.6;color:${C.ink};word-break:break-word;overflow-wrap:anywhere;${extra}">${inner}</p>`;

const link = (href: string, label: string) =>
  `<a href="${href}" style="color:${C.indigo};text-decoration:underline;">${label}</a>`;

/** A label/value table with hairline rows. Values must already be escaped HTML. */
function details(rows: Array<[string, string | null | undefined | false]>): string {
  const kept = rows.filter(([, v]) => v) as Array<[string, string]>;
  if (!kept.length) return '';
  const tr = kept
    .map(
      ([label, value], i) =>
        `<tr><td valign="top" width="38%" style="padding:9px 12px 9px 0;${i ? `border-top:1px solid ${C.hairline};` : ''}font-family:${SANS};font-size:13px;line-height:1.45;font-weight:bold;color:${C.muted};">${label}</td><td valign="top" style="padding:9px 0;${i ? `border-top:1px solid ${C.hairline};` : ''}font-family:${SANS};font-size:15px;line-height:1.5;color:${C.ink};word-break:break-word;">${value}</td></tr>`,
    )
    .join('');
  return `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="border-collapse:collapse;">${tr}</table>`;
}

